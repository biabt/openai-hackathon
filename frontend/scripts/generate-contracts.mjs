import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const backendRoot = resolve(frontendRoot, "../backend");
const checkOnly = process.argv.includes("--check");

const sources = {
  schema: firstExisting([
    resolve(backendRoot, "schema/city-os.schema.json"),
    resolve(frontendRoot, "contracts/city-os.schema.snapshot.json"),
  ]),
  bootstrap: firstExisting([
    resolve(backendRoot, "tests/fixtures/contracts/bootstrap.json"),
    resolve(frontendRoot, "contracts/fixtures/bootstrap.json"),
  ]),
  stream: firstExisting([
    resolve(backendRoot, "tests/fixtures/contracts/stream.jsonl"),
    resolve(frontendRoot, "contracts/fixtures/stream.jsonl"),
  ]),
};

const targets = {
  schema: resolve(frontendRoot, "src/lib/contracts/schema.json"),
  generated: resolve(frontendRoot, "src/lib/contracts/generated.ts"),
  bootstrap: resolve(frontendRoot, "src/lib/contracts/fixtures/bootstrap.json"),
  stream: resolve(frontendRoot, "src/lib/contracts/fixtures/stream.jsonl"),
  streamJson: resolve(frontendRoot, "src/lib/contracts/fixtures/stream.json"),
};

for (const [name, source] of Object.entries(sources)) {
  if (!source) throw new Error(`Missing ${name} contract source. Expected backend C0 or the committed local snapshot.`);
}

const schema = JSON.parse(await readFile(sources.schema, "utf8"));
const bootstrap = JSON.parse(await readFile(sources.bootstrap, "utf8"));
const stream = (await readFile(sources.stream, "utf8"))
  .split(/\r?\n/u)
  .filter(Boolean)
  .map((line, index) => {
    try { return JSON.parse(line); }
    catch (error) { throw new Error(`Invalid stream JSONL at line ${index + 1}`, { cause: error }); }
  });

const expected = new Map([
  [targets.schema, `${stableJson(schema)}\n`],
  [targets.generated, renderTypes(schema)],
  [targets.bootstrap, `${stableJson(bootstrap)}\n`],
  [targets.stream, `${stream.map((frame) => stableJson(frame, 0)).join("\n")}\n`],
  [targets.streamJson, `${stableJson(stream)}\n`],
]);

const stale = [];
for (const [target, content] of expected) {
  if (checkOnly) {
    const current = existsSync(target) ? await readFile(target, "utf8") : null;
    if (current !== content) stale.push(target.slice(frontendRoot.length + 1));
    continue;
  }
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, "utf8");
}

if (stale.length > 0) {
  throw new Error(`Generated contracts are stale:\n${stale.map((path) => `  - ${path}`).join("\n")}\nRun npm run contracts:generate.`);
}

console.log(checkOnly ? "Contract artifacts are current." : `Generated contracts from ${sources.schema.slice(frontendRoot.length + 1)}.`);

function firstExisting(paths) {
  return paths.find((path) => existsSync(path));
}

function stableJson(value, spaces = 2) {
  return JSON.stringify(sortKeys(value), null, spaces);
}

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value === null || typeof value !== "object") return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, sortKeys(value[key])]));
}

function renderTypes(rootSchema) {
  const definitions = rootSchema.$defs ?? rootSchema.definitions;
  if (!definitions || typeof definitions !== "object") throw new Error("Contract schema has no $defs/definitions section.");
  const declarations = Object.entries(definitions).map(([name, definition]) => declaration(name, definition)).join("\n\n");
  return `/* eslint-disable */\n// Generated by scripts/generate-contracts.mjs. Do not edit by hand.\n// Source: backend/schema/city-os.schema.json, with a committed C0-compatible offline snapshot.\n\n${declarations}\n`;
}

function declaration(name, schema) {
  const safeName = identifier(name);
  if (schema.type === "object" && schema.properties) {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties).map(([key, value]) =>
      `  ${propertyName(key)}${required.has(key) ? "" : "?"}: ${toType(value)};`,
    );
    return `export interface ${safeName} {\n${fields.join("\n")}\n}`;
  }
  return `export type ${safeName} = ${toType(schema)};`;
}

function toType(schema) {
  if (!schema || typeof schema !== "object") return "unknown";
  if (schema.$ref) return identifier(schema.$ref.split("/").at(-1));
  if (Object.hasOwn(schema, "const")) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if (schema.anyOf) return schema.anyOf.map(toType).join(" | ");
  if (schema.oneOf) return schema.oneOf.map(toType).join(" | ");
  if (schema.allOf) return schema.allOf.map(toType).join(" & ");
  if (Array.isArray(schema.type)) return schema.type.map((type) => toType({ ...schema, type })).join(" | ");
  if (schema.type === "string") return "string";
  if (schema.type === "number" || schema.type === "integer") return "number";
  if (schema.type === "boolean") return "boolean";
  if (schema.type === "null") return "null";
  if (schema.type === "array") {
    if (schema.prefixItems) return `[${schema.prefixItems.map(toType).join(", ")}]`;
    return `Array<${toType(schema.items ?? {})}>`;
  }
  if (schema.type === "object" || schema.properties) {
    const required = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(([key, value]) =>
      `${propertyName(key)}${required.has(key) ? "" : "?"}: ${toType(value)}`,
    );
    if (schema.additionalProperties && typeof schema.additionalProperties === "object") {
      fields.push(`[key: string]: ${toType(schema.additionalProperties)}`);
    }
    return `{ ${fields.join("; ")} }`;
  }
  return "unknown";
}

function identifier(value) {
  const result = value.replace(/[^A-Za-z0-9_$]/gu, "_");
  return /^[A-Za-z_$]/u.test(result) ? result : `_${result}`;
}

function propertyName(value) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(value) ? value : JSON.stringify(value);
}
